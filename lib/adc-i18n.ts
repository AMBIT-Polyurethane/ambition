export const unitName = (unit: string | null | undefined, lang: Lang) => {
  const u = (unit ?? "each").toLowerCase();
  const out = lang === "es" ? UNITS_ES[u] ?? u : lang === "zh" ? UNITS_ZH[u] ?? u : u;
  return out.replace(/^\w/, (c) => c.toUpperCase());
};

