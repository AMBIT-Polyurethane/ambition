export const errText = (msg: string, lang: Lang) => {
  // The pick up only / truckload messages carry part numbers: show the start in the shopper's language.
  if (lang !== "en" && /^Some items are pick up only/.test(msg)) return dict(lang).pickupOnly(msg.replace(/^.*?:\s*/, "").replace(/\. Please.*$/, ""));
  return lang === "es" ? ERR_ES[msg] ?? msg : lang === "zh" ? ERR_ZH[msg] ?? msg : msg;
};

/** Long dates the way each language says them ("Sunday, November 30" / "domingo, 30 de noviembre"). */
export const longDay = (isoDate: string, lang: Lang) =>
  new Date(`${isoDate}T12:00:00Z`).toLocaleDateString(lang === "es" ? "es-US" : lang === "zh" ? "zh-CN" : "en-US", { weekday: "long", month: "long", day: "numeric", timeZone: "UTC" });
