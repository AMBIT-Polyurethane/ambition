"""Cut a small picture of each part out of the parts diagrams, for parts that have no catalog photo
(the ADC cart shows them). Run from the repo root:  python3 scripts/diagram_thumbs.py
Writes public/diagrams/thumbs/<sku>.webp and lib/diagram-thumbs.ts."""
import json, os, re, subprocess, sys
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public/diagrams/thumbs")
SIZE = 256

DUMP = r'''
const ts=require("typescript"),fs=require("fs"),os=require("os"),path=require("path");
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"dg-"));
for (const f of ["lib/diagrams.ts","lib/diagram-fusion.ts","lib/diagram-shapes-st1.ts"]) {
  const src=fs.readFileSync(f,"utf8").replace(/from "@\/lib\/([^"]+)"/g,(m,a)=>`from "./${a}.js"`);
  fs.writeFileSync(path.join(tmp,path.basename(f).replace(".ts",".js")),ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText);
}
const {DIAGRAMS}=require(path.join(tmp,"diagrams.js"));
process.stdout.write(JSON.stringify(DIAGRAMS.map(d=>({slug:d.slug,image:d.image,w:d.w,parts:d.parts.map(p=>({sku:p.sku,at:p.at??null,shapes:p.shapes??null}))}))));
'''

def polys(path):
    out = []
    for sub in re.split(r"(?=M)", path):
        nums = list(map(float, re.findall(r"-?\d+(?:\.\d+)?", sub)))
        pts = list(zip(nums[0::2], nums[1::2]))
        if len(pts) >= 3: out.append(pts)
    return out

def bbox(pts):
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)

def area(pts):
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))) / 2

def main():
    os.chdir(ROOT)
    diagrams = json.loads(subprocess.run(["node", "-e", DUMP], capture_output=True, text=True, check=True).stdout)
    os.makedirs(OUT, exist_ok=True)
    made = {}
    for d in diagrams:
        img = Image.open(os.path.join(ROOT, "public" + d["image"])).convert("RGB")
        k = img.width / d["w"]
        for p in d["parts"]:
            sku = p["sku"]
            if sku in made or not (p["shapes"] or p["at"]): continue
            if p["shapes"]:
                ps = [q for s in p["shapes"] for q in polys(s)]
                big = max(ps, key=area)
                bx0, by0, bx1, by1 = bbox(big); m = 0.25 * max(bx1 - bx0, by1 - by0)
                keep = [q for q in ps if not (bbox(q)[0] > bx1 + m or bbox(q)[2] < bx0 - m or bbox(q)[1] > by1 + m or bbox(q)[3] < by0 - m)]
                x0, y0, x1, y1 = bbox([pt for q in keep for pt in q])
                mask = Image.new("L", img.size, 0); dr = ImageDraw.Draw(mask)
                for q in keep: dr.polygon([(x * k, y * k) for x, y in q], fill=255)
                mask = mask.filter(ImageFilter.MaxFilter(max(3, int(2 * k) | 1))).filter(ImageFilter.GaussianBlur(0.8))
                part = Image.composite(img, Image.new("RGB", img.size, "white"), mask)
            else:  # only a dot: a plain crop around it
                cx, cy = p["at"][0]; r = 45
                x0, y0, x1, y1 = cx - r, cy - r, cx + r, cy + r
                part = img
            w, h = (x1 - x0) * k, (y1 - y0) * k; side = max(w, h) * 1.14 + 8
            cx, cy = (x0 + x1) / 2 * k, (y0 + y1) / 2 * k
            box = (cx - side / 2, cy - side / 2, cx + side / 2, cy + side / 2)
            canvas = Image.new("RGB", (int(side), int(side)), "white")
            src = part.crop(tuple(int(round(v)) for v in box))
            canvas.paste(src, (0, 0))
            name = re.sub(r"[^A-Za-z0-9_-]", "_", sku)
            canvas.resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(OUT, f"{name}.webp"), quality=88, method=6)
            made[sku] = name
    entries = ",\n  ".join(f'{json.dumps(s)}: {json.dumps(n)}' for s, n in sorted(made.items()))
    open(os.path.join(ROOT, "lib/diagram-thumbs.ts"), "w").write(
        "// Generated by scripts/diagram_thumbs.py from the parts diagrams. Do not edit by hand.\n\n"
        f"const FILES: Record<string, string> = {{\n  {entries},\n}};\n\n"
        "/** A picture of the part cut from its parts diagram (for parts with no catalog photo), or null. */\n"
        "export function diagramThumb(sku: string): string | null {\n  const f = FILES[sku];\n  return f ? `/diagrams/thumbs/${f}.webp` : null;\n}\n")
    print(len(made), "thumbs")

if __name__ == "__main__":
    main()
